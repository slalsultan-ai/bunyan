export function formatPersonalInteractivePost(q: {
  questionText: string;
  options: Array<{ text: string }>;
  correctIndex: number;
  explanation: string;
  subSkill: string;
}): { content: string; comment: string } {
  const letters = ['أ', 'ب', 'ج', 'د'];

  const optionsText = q.options
    .map((o, i) => `${letters[i]}) ${o.text}`)
    .join('\n');

  const content = `سؤال حليته مع أولادي أمس وحبيت أشاركه معاكم:

${q.questionText}

${optionsText}

تلميحة: ${getHint(q.subSkill)}

شاركونا إجاباتكم في التعليقات! الإجابة الصحيحة بنزّلها في أول تعليق.

هذا النوع من الأسئلة يقيس مهارة ${q.subSkill} — ومن أكثر المهارات اللي تتكرر في اختبار القدرات.

#تحدي #قدرات #سؤال_اليوم`;

  const comment = `الإجابة الصحيحة: ${letters[q.correctIndex]}) ${q.options[q.correctIndex].text}

الشرح:
${q.explanation}

أحسنتوا كلكم اللي حاولتوا! المحاولة أهم من الإجابة الصحيحة.`;

  return { content, comment };
}

