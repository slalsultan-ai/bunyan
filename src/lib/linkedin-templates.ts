// Day of week → post type (0=Sunday in JS, but we map Saturday=6 first)
export function getPostTypeForDate(date: Date): PostType {
  const day = date.getDay(); // 0=Sun,1=Mon,...6=Sat
  const map: Record<number, PostType> = {
    6: 'quantitative_tip',   // السبت
    0: 'verbal_tip',         // الأحد
    1: 'logical_tip',        // الإثنين
    2: 'interactive_question',// الثلاثاء
    3: 'stat_tip',           // الأربعاء
    4: 'parenting_tip',      // الخميس
    5: 'motivational',       // الجمعة
  };
  return map[day];
}

